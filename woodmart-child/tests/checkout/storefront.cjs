/* Uses the disposable local WooCommerce seeded by tests/checkout/seed.php. */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.CHECKOUT_TEST_URL || 'http://127.0.0.1:8787';
const cartPath = process.env.CHECKOUT_TEST_CART_PATH || '/cart/';
const shopPath = process.env.CHECKOUT_TEST_SHOP_PATH || '/shop/';
const checkoutPath = process.env.CHECKOUT_TEST_CHECKOUT_PATH || '/checkout/';
assert(['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname));
(async () => {
    const browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await page.goto(base + cartPath, { waitUntil: 'networkidle' });
    assert(page.url() !== base + cartPath, 'Empty cart must go to shop without a redirect loop.');
    await page.goto(base + '/?mitkin_test_cart=physical', { waitUntil: 'networkidle' });
    await page.goto(base + cartPath, { waitUntil: 'networkidle' });
    assert(page.url().includes(checkoutPath), 'Cart route did not skip straight to checkout.');
    await page.goto(base + shopPath, { waitUntil: 'networkidle' });
    let requests = 0;
    await page.route(/wc-ajax=add_to_cart/, async route => {
        requests += 1;
        await new Promise(resolve => setTimeout(resolve, 1000));
        await route.continue();
    });
    const button = page.locator('a.ajax_add_to_cart[data-product_id="12"]').first();
    await button.locator('xpath=ancestor::*[contains(concat(" ",normalize-space(@class)," ")," wd-product ")]').hover();
    await page.waitForTimeout(400);
    const response = page.waitForResponse(r => r.url().includes('wc-ajax=add_to_cart'));
    await button.click();
    await page.locator('.cart-widget-side.wd-opened.mitkin-cart-pending').waitFor({ timeout: 900 });
    assert.equal(await page.locator('.cart-widget-side').getAttribute('aria-busy'), 'true');
    assert.match(await page.locator('.mitkin-cart-status').innerText(), /Добавляем/);
    const json = await (await response).json();
    assert(!json.error);
    await page.waitForFunction(() => document.querySelector('.cart-widget-side')?.getAttribute('aria-busy') === 'false');
    assert.equal(requests, 1, 'One click sent duplicate cart requests.');
    assert(await page.locator('.cart-widget-side').evaluate(e => e.classList.contains('wd-opened')), 'Response toggled the drawer closed.');
    assert.equal(await page.locator('.cart-widget-side .woocommerce-mini-cart__buttons a').count(), 1, 'There must be one primary CTA.');
    assert.equal((await page.locator('.cart-widget-side .woocommerce-mini-cart__total strong').innerText()).trim(), 'Итого:');
    const checkout = page.locator('.cart-widget-side a.checkout');
    assert((await checkout.getAttribute('href')).includes(checkoutPath));
    assert.equal(await checkout.evaluate(e => getComputedStyle(e).backgroundColor), 'rgb(72, 79, 50)');
    await page.screenshot({ path: '/tmp/mitkin-cart-branded-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    const drawer = await page.locator('.cart-widget-side').boundingBox();
    assert(drawer.width <= 390);
    await page.screenshot({ path: '/tmp/mitkin-cart-branded-mobile.png', fullPage: true });
    await checkout.click();
    await page.waitForURL(url => url.href.includes(checkoutPath));
    console.log('PASS: cart bypass, empty cart, immediate pending feedback, one native request, stable open drawer, one green checkout CTA, mobile width.');
    await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
